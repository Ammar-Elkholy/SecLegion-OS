"""seclegion-aichat: SecLegion's wrapper around aichat (optdepend).

  seclegion-aichat [aichat args]   regenerate ~/.config/aichat/config.yaml, then run aichat
  seclegion-aichat config          only regenerate the config
  seclegion-aichat docs [question] ask the docs-RAG role with /usr/share/doc/seclegion attached

The generated yaml never holds an API key. aichat reads a client's key from the environment
variable <CLIENT_NAME>_API_KEY when the yaml has none, so the wrapper reads the one key it needs
from the Secret Service (secret-tool, schema org.seclegion.ai) and puts it into the aichat
process environment only. The key is never printed or logged.

Pipe guard: piped or redirected stdin is never sent to a cloud client unless a person confirms
on /dev/tty (y/N); with no terminal the send is refused. Local ollama is always allowed.
Serve mode (aichat --serve) is not shipped: aichat has no CORS setting, so a browser page
could not be refused; the wrapper rejects it.
"""

import json
import os
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

LOCAL = "ollama"
LOCAL_BASE = "http://127.0.0.1:11434/v1"
SCHEMA = "org.seclegion.ai"
ROLES_SRC = Path("/usr/share/seclegion/aichat/roles")
DOCS = Path("/usr/share/doc/seclegion")
NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,40}$")


class Refused(Exception):
    pass


def xdg_config(env):
    return Path(env.get("XDG_CONFIG_HOME") or Path(env.get("HOME", "~")).expanduser() / ".config")


def key_env_name(client):
    return re.sub(r"[^A-Za-z0-9]", "_", client).upper() + "_API_KEY"


def load_providers(env):
    try:
        data = tomllib.loads((xdg_config(env) / "seclegion" / "ai.toml").read_text())
    except (FileNotFoundError, tomllib.TOMLDecodeError):
        return []
    out = []
    for p in data.get("provider", []):
        if NAME_RE.match(str(p.get("name", ""))) and p.get("base_url"):
            out.append(
                {
                    "name": p["name"],
                    "base_url": p["base_url"],
                    "model": p.get("model", ""),
                    "auth": p.get("auth", "bearer"),
                }
            )
    return out


def runtime_state():
    """seclegion-ai status --json, or an all-off state when it cannot be read."""
    off = {"enabled": False, "installed": False, "listening": False, "models": []}
    try:
        p = subprocess.run(["seclegion-ai", "status", "--json"], capture_output=True, text=True, timeout=10)
        d = json.loads(p.stdout)
    except (OSError, ValueError, subprocess.SubprocessError):
        return off
    return d if isinstance(d, dict) else off


def local_models(state):
    if not (state.get("enabled") and state.get("listening")):
        return [], []
    names = [m for m in state.get("models", []) if isinstance(m, str)]
    emb = [m for m in names if "embed" in m]
    return [m for m in names if m not in emb], emb


def default_model(providers, state):
    chat, _ = local_models(state)
    if chat:
        return f"{LOCAL}:{chat[0]}"
    for p in providers:
        if p["model"]:
            return f"{p['name']}:{p['model']}"
    return None


def q(s):
    return json.dumps(s)  # a JSON string is a valid YAML double-quoted scalar


def build_config(providers, state):
    """aichat config.yaml text. Holds no api_key line at all."""
    chat, emb = local_models(state)
    lines = [
        "# Generated by seclegion-aichat. Do not edit: it is rewritten on every launch.",
        "# No API keys here: they come from the Secret Service into the process environment.",
        "save: false",
    ]
    dm = default_model(providers, state)
    if dm:
        lines.append(f"model: {q(dm)}")
    if emb:
        lines.append(f"rag_embedding_model: {q(LOCAL + ':' + emb[0])}")
    lines.append("clients:")
    n0 = len(lines)
    if chat or emb:
        lines += [
            "  - type: openai-compatible",
            f"    name: {LOCAL}",
            f"    api_base: {q(LOCAL_BASE)}",
            "    models:",
        ]
        lines += [f"      - name: {q(m)}" for m in chat]
        lines += [f"      - name: {q(m)}\n        type: embedding" for m in emb]
    for p in providers:
        if p["auth"] == "x-api-key":
            lines += ["  - type: claude", f"    name: {p['name']}", f"    api_base: {q(p['base_url'])}"]
        else:
            lines += [
                "  - type: openai-compatible",
                f"    name: {p['name']}",
                f"    api_base: {q(p['base_url'])}",
            ]
        lines.append("    models:")
        if p["model"]:
            lines.append(f"      - name: {q(p['model'])}")
    if len(lines) == n0:
        lines[-1] = "clients: []"
    return "\n".join(lines) + "\n"


def write_config(env, providers, state, roles_src=ROLES_SRC):
    cdir = Path(env.get("AICHAT_CONFIG_DIR") or xdg_config(env) / "aichat")
    cdir.mkdir(parents=True, exist_ok=True)
    cfg = cdir / "config.yaml"
    fd = os.open(cfg, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(build_config(providers, state))
    if Path(roles_src).is_dir():
        rd = cdir / "roles"
        rd.mkdir(exist_ok=True)
        for r in Path(roles_src).glob("*.md"):
            shutil.copyfile(r, rd / r.name)
    return cdir


def pick_model(args, env, default):
    """(model id the run will use, whether the user chose it): -m/--model, AICHAT_MODEL, else default."""
    for i, a in enumerate(args):
        if a in ("-m", "--model") and i + 1 < len(args):
            return args[i + 1], True
        if a.startswith("--model="):
            return a.split("=", 1)[1], True
    if env.get("AICHAT_MODEL"):
        return env["AICHAT_MODEL"], True
    return default, False


def secret_lookup(client):
    try:
        p = subprocess.run(
            ["secret-tool", "lookup", "xdg:schema", SCHEMA, "provider", client],
            capture_output=True,
            text=True,
            check=False,
        )
    except FileNotFoundError:
        return None
    return p.stdout if p.returncode == 0 and p.stdout else None


def tty_open():
    try:
        return open("/dev/tty", "r+")
    except OSError:
        return None


def main(
    argv=None,
    env=None,
    stdin_isatty=None,
    open_tty=tty_open,
    launch=None,
    get_secret=secret_lookup,
    state_fn=runtime_state,
    roles_src=ROLES_SRC,
):
    args = list(sys.argv[1:] if argv is None else argv)
    env = dict(os.environ if env is None else env)
    isatty = (sys.stdin.isatty() if sys.stdin else False) if stdin_isatty is None else stdin_isatty
    try:
        return _run(args, env, isatty, open_tty, launch, get_secret, state_fn, roles_src)
    except Refused as e:
        print(f"seclegion-aichat: {e}", file=sys.stderr)
        return 1


def _run(args, env, isatty, open_tty, launch, get_secret, state_fn, roles_src):
    if any(a == "--serve" or a.startswith("--serve=") for a in args):
        raise Refused(
            "refused: serve mode is not shipped (aichat has no CORS control, so cross-origin "
            "browser requests could not be refused)"
        )
    providers, state = load_providers(env), state_fn()
    cdir = write_config(env, providers, state, roles_src)
    if args[:1] == ["config"]:
        print(f"wrote {cdir / 'config.yaml'}")
        return 0
    if args[:1] == ["docs"]:
        args = ["-r", "docs-RAG"] + (["-f", str(DOCS)] if DOCS.exists() else []) + args[1:]
    model, explicit = pick_model(args, env, default_model(providers, state))
    if not model:
        raise Refused("no model: enable the local runtime (seclegion-ai enable) or add a provider")
    if not explicit:
        args = ["-m", model] + args  # an explicit -m also beats any model a role file names
    client = model.split(":", 1)[0] if ":" in model else ""
    penv = dict(env)
    if client != LOCAL:  # anything that is not the local ollama client is treated as cloud
        if not isatty:
            tty = open_tty()
            if tty is None:
                raise Refused(
                    f"refused: piped or redirected input is never sent to cloud model {model} "
                    "without an interactive confirmation (no terminal available)"
                )
            with tty:
                tty.write(f"Send piped input to cloud model {model}? [y/N] ")
                tty.flush()
                ans = tty.readline().strip().lower()
            if ans not in ("y", "yes"):
                raise Refused("refused: not confirmed")
        key = get_secret(client) if client else None
        if not key:
            raise Refused(f"no API key for {client or model} in the Secret Service (AI Center)")
        penv[key_env_name(client)] = key
    penv["AICHAT_CONFIG_DIR"] = str(cdir)
    penv["AICHAT_ROLES_DIR"] = str(cdir / "roles")
    binary = env.get("SECLEGION_AICHAT_BIN") or shutil.which("aichat", path=env.get("PATH"))
    if not binary:
        raise Refused("aichat is not installed (pacman -S aichat)")
    cmd = [binary] + args
    if launch is not None:
        return launch(cmd, penv)
    os.execve(binary, cmd, penv)


if __name__ == "__main__":
    sys.exit(main())
