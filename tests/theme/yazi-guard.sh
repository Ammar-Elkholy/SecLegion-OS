# G5: the yazi hook through the real CLI, in a scratch world. It must create
# theme.toml where absent, replace a file whose first line is our marker (backing
# up edits made since we wrote it), adopt a hand-made file on the first run by
# moving it byte-for-byte to theme.toml.seclegion-orig, and leave it alone once
# that backup exists. Stub-only PATH (no
# swaync-client, systemctl, hyprctl, yazi) and no Wayland/Hyprland env, so no
# other hook can touch the live session; every path is under a temp dir.
set -uo pipefail
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf -- "$WORK"' EXIT
for v in $(env | sed -n 's/^\(GIT_[A-Za-z_]*\)=.*/\1/p'); do unset "$v"; done
unset WAYLAND_DISPLAY HYPRLAND_INSTANCE_SIGNATURE

fail() { echo "FAIL: $*" >&2; exit 1; }
mkdir -p "$WORK/bin" "$WORK/state" "$WORK/run" "$WORK/yazi"
chmod 700 "$WORK/run"
MARK="# generated by seclegion-theme"
T="$WORK/yazi/theme.toml"

run() {
    PATH="$WORK/bin" XDG_STATE_HOME="$WORK/state" XDG_RUNTIME_DIR="$WORK/run" \
        YAZI_CONFIG_HOME="$WORK/yazi" /usr/bin/python3 "$SRC/tools/seclegion-theme" reset >"$WORK/out" 2>&1 \
        || { cat "$WORK/out" >&2; fail "reset exited non-zero"; }
}

# 1. absent -> created, ours
run
[ -f "$T" ] && [ ! -L "$T" ] || fail "theme.toml not created"
[ "$(head -n1 "$T")" = "$MARK" ] || fail "created file lacks the marker"

# 2. marker file (even with a later hand tweak) -> replaced
printf '%s\n# my tweak\n' "$MARK" > "$T"
run
grep -q 'my tweak' "$T" && fail "marker file was not replaced"
[ "$(head -n1 "$T")" = "$MARK" ] || fail "replaced file lacks the marker"

# 3. hand-made (no marker, old [manager] section), first run -> adopted: the
#    exact original bytes move to .seclegion-orig, ours takes its place
O="$T.seclegion-orig"
printf '[manager]\n# hand made\n' > "$T"
cp "$T" "$WORK/orig-bytes"
run
cmp -s "$O" "$WORK/orig-bytes" || fail ".seclegion-orig is not the exact original bytes"
[ "$(head -n1 "$T")" = "$MARK" ] || fail "adopted theme.toml lacks the marker"
grep -q 'hook yazi: adopted' "$WORK/out" || fail "no 'adopted' note"
grep -q "mv $O $T" "$WORK/out" || fail "adopted note lacks the restore command"

# 4. the user restores a hand-made file with .seclegion-orig present -> kept, untouched
printf '[mgr]\n# restored\n' > "$T"
before="$(sha256sum "$T")"
run
[ "$(sha256sum "$T")" = "$before" ] || fail "hand-edited theme.toml was modified"
cmp -s "$O" "$WORK/orig-bytes" || fail ".seclegion-orig changed"
grep -q 'hook yazi: kept' "$WORK/out" || fail "no 'kept' note for the hand-edited file"

# 5. a marker file edited since our last write -> saved to .seclegion-bak, replaced
printf '%s\n# my tweak\n' "$MARK" > "$T"
run   # no sidecar match yet is fine: replaced normally; now write ours and edit it
printf '# tweak after the write\n' >> "$T"
run
grep -q 'tweak after the write' "$T.seclegion-bak" || fail "edited marker file was not backed up"
grep -q 'tweak after the write' "$T" && fail "edited marker file was not replaced"
grep -q 'hook yazi: ok-backed-up' "$WORK/out" || fail "no 'ok-backed-up' note"
[ -z "$(find "$WORK/yazi" -name '.theme.toml*')" ] || fail "temp file left behind"

echo yazi-guard-ok
