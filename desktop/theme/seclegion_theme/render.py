def _osd_defines(t) -> list[str]:
    """sl_osd_*: swayosd's own sheet and the swaync popup that shows volume and
    brightness (a low-urgency notification with an int:value bar)."""
    r, g, b = C.hex_to_rgb(t["bg"])
    tr, tg, tb = C.hex_to_rgb(t["text"])
    return [
        f"@define-color sl_osd_bg rgba({r}, {g}, {b}, 0.93);",
        f"@define-color sl_osd_fg {t['accent']};",
        f"@define-color sl_osd_frame {t['accent2']};",
        f"@define-color sl_osd_bar {t['accent']};",
        f"@define-color sl_osd_track rgba({tr}, {tg}, {tb}, 0.12);",
    ]


def _swayosd(t) -> str:
    rows = _defines(t) + _osd_defines(t)
    return "\n".join([_head("/* {} */")] + rows) + "\n"


