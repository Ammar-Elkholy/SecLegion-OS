# File-manager look (Thunar/GTK, Dolphin/KDE+Qt, yazi). Each renderer below
# re-validates every value it uses through _h6() (-> _hex()), so a token that
# reached it without _checked() is still refused. Text pairs keep their
# backgrounds in {bg, surface} (and surface2 for text/muted only): those are
# the pairs palette._rules() guarantees.

def _h6(value: str) -> str:
    """#rrggbb only: these formats take opaque colours (an alpha pair would
    turn into a wrong colour in KDE r,g,b or qt6ct #aarrggbb)."""
    digits = _hex(value)
    if GUARD_ENABLED and len(digits) != 6:
        raise ThemeError(f"expected #rrggbb, got {value!r}")
    return "#" + digits


def _named(pairs) -> list[str]:
    return [f"@define-color {name} {_h6(v)};" for name, v in pairs]


