    out = [YAZI_MARKER, "# SPDX-License-Identifier: MIT",
    # REUSE-IgnoreEnd
           "# Edits here are saved to theme.toml.seclegion-bak and replaced on the next apply."]
    for name, keys in sections.items():
        out += ["", f"[{name}]"] + [f"{k} = {v}" for k, v in keys.items()]

    def rule(match, *a, **k):
        return "  { " + match + ", " + _yfields(t, *a, **k) + " },"

