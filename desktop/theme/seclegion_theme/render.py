"""Render the output files from final tokens.

Injection safety: every colour that reaches a template goes through `_hex()`,
which accepts only a full match of [0-9a-f]{6}([0-9a-f]{2})? (fullmatch: a
trailing newline does not pass, unlike `$`). Template keys come from the
fixed TOKEN_NAMES list, never from input. The only free-form values (mode,
wallpaper path) are written solely through json.dumps into colors.json.
"""
from __future__ import annotations

import functools
import json
import re

from . import color as C
from .palette import TOKEN_NAMES, ThemeError, load_defaults

SCHEMA = 1
_HEX_RE = re.compile(r"[0-9a-f]{6}(?:[0-9a-f]{2})?")
# Test hook: the guard-mutation run (SL_THEME_TEST_NOGUARD=1) flips this to
# prove the injection tests notice a missing guard. Never read from the env here.
GUARD_ENABLED = True

FILES = (
    "colors.json", "colors.css", "hyprland-colors.lua", "kitty-colors.conf",
    "rofi-colors.rasi", "hyprlock-colors.conf", "swaync-colors.css",
    "swayosd-colors.css", "starship-palette.toml", "starship.toml",
    "gtk3.css", "gtk4.css", "kde.colors", "qt6ct.conf", "yazi-theme.toml", "regreet.css",
)

_HEADER = "generated by seclegion-theme; do not edit"


def _head(comment: str) -> str:
    """SPDX + generated-file header in one comment syntax ('# {}', '/* {} */')."""
    # REUSE-IgnoreStart
    return comment.format("SPDX-License-Identifier: MIT") + "\n" + comment.format(_HEADER)
    # REUSE-IgnoreEnd


def _hex(value: str, alpha: str = "") -> str:
    """Validated lowercase hex digits (no '#'), optionally with an alpha suffix."""
    if not isinstance(value, str):
        raise ThemeError("colour token is not a string")
    v = value[1:] if value.startswith("#") else value
    if GUARD_ENABLED and not _HEX_RE.fullmatch(v):
        raise ThemeError(f"refusing to render invalid colour token: {value!r}")
    return v + alpha


def _h(value: str) -> str:
    return "#" + _hex(value)


def _rgba(value: str, alpha: str = "ff") -> str:
    digits = _hex(value)
    if len(digits) != 6:
        raise ThemeError(f"expected #rrggbb, got {value!r}")
    if not re.fullmatch(r"[0-9a-f]{2}", alpha):
        raise ThemeError(f"invalid alpha {alpha!r}")
    return "rgba(" + digits + alpha + ")"


def _checked(tokens: dict[str, str]) -> dict[str, str]:
    return {k: _h(tokens[k]) for k in TOKEN_NAMES}


def _defines(t: dict[str, str]) -> list[str]:
    return [f"@define-color sl_{k} {t[k]};" for k in TOKEN_NAMES]


def _json(t, mode, requested_mode, contrast, source) -> str:
    return json.dumps(
        {
            "schema": SCHEMA,
            "mode": mode,
            "requested_mode": requested_mode,
            "contrast": contrast,
            "source": source,
            "tokens": t,
        },
        indent=2,
        sort_keys=True,
    ) + "\n"


def _css(t) -> str:
    return "\n".join([_head("/* {} */")] + _defines(t)) + "\n"


def _lua(t) -> str:
    # Literal strings only; loads under pcall(dofile, ...). rgba(rrggbbaa) is
    # the only colour form (0x... would reintroduce the ARGB/RGBA bug).
    ent = {
        "active_border": _rgba(t["border_active"]),
        "inactive_border": _rgba(t["border_inactive"]),
        "bg": _rgba(t["bg"]),
        "surface": _rgba(t["surface"]),
        "text": _rgba(t["text"]),
        "accent": _rgba(t["accent"]),
        "accent2": _rgba(t["accent2"]),
        "crit": _rgba(t["crit"]),
        "shadow": _rgba(t["bg"], "ee"),
    }
    body = "".join(f'  {k} = "{v}",\n' for k, v in ent.items())
    return _head("-- {}") + f"\nreturn {{\n{body}}}\n"


def _kitty(t) -> str:
    lines = [
        _head("# {}"),
        f"foreground {t['text']}",
        f"background {t['bg']}",
        f"selection_foreground {t['bg']}",
        f"selection_background {t['accent']}",
        f"cursor {t['accent']}",
        f"cursor_text_color {t['bg']}",
        f"url_color {t['accent2']}",
        f"active_border_color {t['border_active']}",
        f"inactive_border_color {t['border_inactive']}",
        f"bell_border_color {t['warn']}",
        f"active_tab_foreground {t['bg']}",
        f"active_tab_background {t['accent']}",
        f"inactive_tab_foreground {t['muted']}",
        f"inactive_tab_background {t['surface']}",
        f"tab_bar_background {t['bg']}",
    ]
    lines += [f"color{i} {t[f'ansi{i}']}" for i in range(16)]
    return "\n".join(lines) + "\n"


def _rasi(t) -> str:
    rows = [f"    sl-{k.replace('_', '-')}: {t[k]};" for k in TOKEN_NAMES]
    rows.append(f"    sl-bg-alpha: {t['bg']}e6;")  # owner rofi bg is #050F0EE6
    return _head("/* {} */") + "\n* {\n" + "\n".join(rows) + "\n}\n"


def _hyprlock(t) -> str:
    rows = [_head("# {}")] + [f"$sl_{k} = {_rgba(t[k])}" for k in TOKEN_NAMES]
    return "\n".join(rows) + "\n"


