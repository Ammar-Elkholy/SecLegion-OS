def _gtk4(t) -> str:
    # Overrides only: the host's ~/.config/gtk-4.0/gtk.css imports the base
    # theme first and this file after it, so nothing here imports anything.
    rows = _named((name, t[tok]) for name, tok in _ADW)
    rows.append(":root {")
    rows += [f"  --{name.replace('_', '-')}: {_h6(t[tok])};" for name, tok in _ADW]
    rows.append("}")
    return "\n".join([_head("/* {} */")] + rows) + "\n"


def _rgb(value: str) -> str:
    return ",".join(str(c) for c in C.hex_to_rgb(_h6(value)))


# KDE colour sets: (BackgroundNormal, BackgroundAlternate) tokens.
_KDE_SETS = (
    ("Window", "bg", "surface"),
    ("View", "surface", "bg"),
    ("Button", "surface", "bg"),
    ("Selection", "accent", "accent"),
    ("Tooltip", "surface", "bg"),
    ("Header", "surface", "bg"),
    ("Complementary", "bg", "surface"),
)
_KDE_FG = (
    ("ForegroundNormal", "text"), ("ForegroundInactive", "muted"), ("ForegroundActive", "accent"),
    ("ForegroundLink", "accent2"), ("ForegroundVisited", "accent"), ("ForegroundNegative", "err"),
    ("ForegroundNeutral", "warn"), ("ForegroundPositive", "ok"),
)


def _kde(t) -> str:
    out = [_head("# {}"), "[General]", "ColorScheme=SecLegion", "Name=SecLegion"]
    for name, normal, alt in _KDE_SETS:
        out += ["", f"[Colors:{name}]",
                f"BackgroundNormal={_rgb(t[normal])}", f"BackgroundAlternate={_rgb(t[alt])}"]
        for key, tok in _KDE_FG:
            # On the accent selection every foreground is the dark base:
            # the semantic colours are not guaranteed against accent.
            out.append(f"{key}={_rgb(t['bg'] if name == 'Selection' else t[tok])}")
        out += [f"DecorationFocus={_rgb(t['border_active'])}", f"DecorationHover={_rgb(t['accent2'])}"]
    return "\n".join(out) + "\n"


# qt6ct colour scheme: 21 entries per group, in QPalette::ColorRole order
