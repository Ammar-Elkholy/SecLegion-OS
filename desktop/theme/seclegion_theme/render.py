# PlaceholderText), each #aarrggbb.
QT_ROLES = (
    "WindowText", "Button", "Light", "Midlight", "Dark", "Mid", "Text", "BrightText",
    "ButtonText", "Base", "Window", "Shadow", "Highlight", "HighlightedText", "Link",
    "LinkVisited", "AlternateBase", "NoRole", "ToolTipBase", "ToolTipText", "PlaceholderText",
)
_QT_ACTIVE = {
    "WindowText": "text", "Button": "surface", "Light": "surface2", "Midlight": "surface2",
    "Dark": "bg", "Mid": "surface", "Text": "text", "BrightText": "accent", "ButtonText": "text",
    "Base": "surface", "Window": "bg", "Shadow": "bg", "Highlight": "accent",
    "HighlightedText": "bg", "Link": "accent2", "LinkVisited": "accent", "AlternateBase": "bg",
    "NoRole": "bg", "ToolTipBase": "surface", "ToolTipText": "text", "PlaceholderText": "muted",
}
_QT_DISABLED = dict(_QT_ACTIVE, WindowText="muted", Text="muted", ButtonText="muted",
                    BrightText="muted", Highlight="surface2", HighlightedText="muted")


def _qt_row(t, roles: dict[str, str]) -> str:
    return ", ".join("#ff" + _h6(t[roles[r]])[1:] for r in QT_ROLES)


def _qt6ct(t) -> str:
    # QSettings INI: ';' is its comment character.
    return "\n".join([
        _head("; {}"), "[ColorScheme]",
        "active_colors=" + _qt_row(t, _QT_ACTIVE),
        "disabled_colors=" + _qt_row(t, _QT_DISABLED),
        "inactive_colors=" + _qt_row(t, _QT_ACTIVE),
    ]) + "\n"


# First line of yazi-theme.toml. The yazi hook replaces ~/.config/yazi/theme.toml
# only when that file is absent or still starts with exactly this line.
YAZI_MARKER = "# generated by seclegion-theme"


def _yfields(t, fg=None, bg=None, **flags) -> str:
    """Fields of one yazi style; colours by token name, flags are fixed `true`s."""
    parts = [f'fg = "{_h6(t[fg])}"'] if fg else []
    if bg:
        parts.append(f'bg = "{_h6(t[bg])}"')
    parts += [f"{k} = true" for k, on in flags.items() if on]
    return ", ".join(parts)


def _ys(t, *a, **k) -> str:
    return "{ " + _yfields(t, *a, **k) + " }"


